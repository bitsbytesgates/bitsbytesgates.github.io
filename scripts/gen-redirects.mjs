#!/usr/bin/env node
/**
 * Emit public/_redirects from src/url-map.json.
 *
 * TWO rules per old post, not one. Cloudflare Pages made the extensionless form canonical in
 * August 2026 by 308-ing every `.html` URL (see forgejo-cloudflare-migration-plan.md F10), so
 * links to BOTH shapes exist in the wild: `.html` in everything published before the move, and
 * extensionless in everything since. Emitting only one form silently 404s the other.
 *
 * Verified on a preview deployment that `_redirects` wins over the Pages asset layer when no
 * competing `.html` asset exists — a single 301 hop, including for comma URLs.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const map = JSON.parse(readFileSync(resolve(root, 'src/url-map.json'), 'utf8'))

const lines = [
  '# Generated by scripts/gen-redirects.mjs — do not edit by hand.',
  '# Two rules per post: the .html form and the extensionless form Cloudflare Pages',
  '# made canonical in Aug 2026. Links to both exist in the wild.',
  '',
]

let n = 0
for (const [oldUrl, newUrl] of Object.entries(map).sort()) {
  const bare = oldUrl.replace(/\.html$/, '')
  lines.push(`${oldUrl}  ${newUrl}  301`)
  lines.push(`${bare}  ${newUrl}  301`)
  n += 2
}

// Standalone Jekyll pages. Their extensionless forms are served directly by Astro
// (/about/ etc.), so only the .html shapes need rules.
lines.push('', '# standalone pages')
const pages = {
  '/index.html': '/',
  '/about.html': '/about/',
  '/archive.html': '/archive/',
  '/series.html': '/series/',
  '/404.html': '/404.html',
  // Astro emits sitemap-index.xml; crawlers still probe the conventional name.
  '/sitemap.xml': '/sitemap-index.xml',
}
for (const [from, to] of Object.entries(pages)) {
  if (from === to) continue
  lines.push(`${from}  ${to}  301`)
  n++
}

const out = resolve(root, 'public/_redirects')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, lines.join('\n') + '\n')
console.log(`wrote ${n} rules -> public/_redirects`)

// Pages caps static rules at 2100; well under, but fail loudly if that ever changes.
if (n > 2000) {
  console.error(`ERROR: ${n} rules exceeds the Cloudflare Pages static-rule limit`)
  process.exit(1)
}
